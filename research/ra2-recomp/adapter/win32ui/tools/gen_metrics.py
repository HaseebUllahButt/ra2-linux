#!/usr/bin/env python3
"""gen_metrics.py: turn reports/wine-metrics.txt (output of tools/probe/probe_metrics.exe under Wine)
into src/wine_metrics.inc: system metrics, system colours, device caps, font metrics."""
import os
H = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
sm, col, caps, fonts = {}, {}, {}, []
for l in open(os.path.join(H, 'reports/wine-metrics.txt')):
    f = l.split()
    if not f: continue
    if f[0] == 'SM': sm[int(f[1])] = int(f[2])
    elif f[0] == 'COLOR': col[int(f[1])] = int(f[2], 16)
    elif f[0] == 'CAPS': caps[int(f[1])] = int(f[2])
    elif f[0] == 'TMALL' and f[1].startswith('font|'):
        name, rest = l.split(None, 1)[1].rsplit('|', 1)[0], l.split(None, 1)[1].rsplit('|', 1)[1]
        _, face, h = name.split('|')
        w, vals = rest.split(None, 1)
        fonts.append((face, int(h), int(w), [int(x) for x in vals.split()]))
    elif f[0] == 'TMALL' and f[1].startswith('stock'):
        fonts.append(('#' + f[1][5:], 0, 0, [int(x) for x in f[2:]]))
o = ['/* generated by tools/gen_metrics.py from reports/wine-metrics.txt (Wine 11, 96 dpi, 1024x768): do not edit */']
o.append('static const int wine_sm[100] = { %s };' % ', '.join(str(sm.get(i, 0)) for i in range(100)))
o.append('static const DWORD wine_color[31] = { %s };' % ', '.join('0x%06x' % col.get(i, 0) for i in range(31)))
o.append('static const int wine_caps[120] = { %s };' % ', '.join(str(caps.get(i, 0)) for i in range(120)))
o.append('/* face ("#n" = stock object n), lfHeight, weight, then tmHeight..tmCharSet (20 values) */')
o.append('static const struct { const char *face; int h, w; int tm[20]; } wine_fonts[] = {')
for face, h, w, tm in fonts:
    o.append('    { "%s", %d, %d, { %s } },' % (face, h, w, ', '.join(map(str, tm))))
o.append('};')
open(os.path.join(H, 'src/wine_metrics.inc'), 'w').write('\n'.join(o) + '\n')
print('fonts', len(fonts))
